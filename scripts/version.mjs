import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const generatedFilePaths = [
  "ComponentCatalogWinUI/Version.props",
  "ComponentCatalogCore/Version.generated.cs",
  "Android/src/version.generated.ts",
  "shared/version.generated.ts",
];

const requiredFilePaths = [
  ...generatedFilePaths,
  "ComponentCatalogWinUI/ComponentCatalogWinUI.csproj",
  "ComponentCatalogCore/Taxonomy/ComponentCategoryTaxonomy.cs",
  "ComponentCatalogWinUI/Services/CatalogStoragePaths.cs",
  "Android/android/app/build.gradle",
  "Android/package.json",
  "Android/src/app-update.ts",
  "Android/src/snapshot-store.ts",
  "shared/catalog.ts",
  "Android/src/components/AboutView.tsx",
  "ComponentCatalogWinUI/Pages/AboutPage.xaml.cs",
  "发布包/Android/app-update.json",
];

function requireString(value, fieldName) {
  if (typeof value !== "string" || !value.trim()) {
    throw new Error(`${fieldName} must be a non-empty string.`);
  }

  return value.trim();
}

function validateVersion(version) {
  if (typeof version !== "object" || version === null || Array.isArray(version)) {
    throw new Error("version.json must contain an object.");
  }

  const productVersion = requireString(version.product?.version, "product.version");
  const taxonomyVersion = requireString(version.taxonomy?.version, "taxonomy.version");
  const androidVersionCode = version.android?.code;

  if (!/^\d+\.\d+$/.test(productVersion)) {
    throw new Error("product.version must use major.minor form.");
  }
  if (!/^\d+$/.test(taxonomyVersion)) {
    throw new Error("taxonomy.version must be a positive integer string.");
  }
  if (!Number.isSafeInteger(androidVersionCode) || androidVersionCode <= 0) {
    throw new Error("android.code must be a positive integer.");
  }

  return {
    product: { version: productVersion },
    android: { code: androidVersionCode },
    taxonomy: { version: taxonomyVersion },
  };
}

export async function readVersionFile(filePath) {
  return validateVersion(JSON.parse(await readFile(filePath, "utf8")));
}

export function expectedGeneratedFiles(version) {
  const normalized = validateVersion(version);
  const { product, android, taxonomy } = normalized;
  const assemblyVersion = `${product.version}.0`;

  return {
    "ComponentCatalogWinUI/Version.props": `<!-- Generated by scripts/version.mjs from version.json. Do not edit manually. -->\n<Project>\n  <PropertyGroup>\n    <Version>${assemblyVersion}</Version>\n    <AssemblyVersion>${assemblyVersion}.0</AssemblyVersion>\n    <FileVersion>${assemblyVersion}.0</FileVersion>\n    <InformationalVersion>${product.version}</InformationalVersion>\n  </PropertyGroup>\n</Project>\n`,
    "ComponentCatalogCore/Version.generated.cs": `// <auto-generated />\n// Generated by scripts/version.mjs from version.json. Do not edit manually.\nnamespace ComponentCatalogCore;\n\npublic static class ProductVersion\n{\n    public const string ProductVersionName = "${product.version}";\n    public const int AndroidVersionCode = ${android.code};\n    public const string TaxonomyVersion = "${taxonomy.version}";\n}\n`,
    "Android/src/version.generated.ts": `// Generated by scripts/version.mjs from version.json. Do not edit manually.\nexport const PRODUCT_VERSION = "${product.version}" as const;\nexport const ANDROID_VERSION_CODE = ${android.code} as const;\nexport const TAXONOMY_VERSION = "${taxonomy.version}" as const;\n`,
    "shared/version.generated.ts": `// Generated by scripts/version.mjs from version.json. Do not edit manually.\nexport const PRODUCT_VERSION = "${product.version}" as const;\nexport const ANDROID_VERSION_CODE = ${android.code} as const;\nexport const TAXONOMY_VERSION = "${taxonomy.version}" as const;\n`,
  };
}

function addMissingExpectation(errors, relativePath, content, expectedText) {
  if (!content.includes(expectedText)) {
    errors.push(`${relativePath} must include ${expectedText}`);
  }
}

export function validateVersionTargets(version, files) {
  const normalized = validateVersion(version);
  const expectedFiles = expectedGeneratedFiles(normalized);
  const errors = [];
  const readTarget = (relativePath) => files[relativePath] ?? "";

  for (const [relativePath, expectedContent] of Object.entries(expectedFiles)) {
    if (readTarget(relativePath) !== expectedContent) {
      errors.push(`${relativePath} is not generated from version.json`);
    }
  }

  addMissingExpectation(errors, "ComponentCatalogWinUI/ComponentCatalogWinUI.csproj", readTarget("ComponentCatalogWinUI/ComponentCatalogWinUI.csproj"), '<Import Project="Version.props"');
  addMissingExpectation(errors, "ComponentCatalogCore/Taxonomy/ComponentCategoryTaxonomy.cs", readTarget("ComponentCatalogCore/Taxonomy/ComponentCategoryTaxonomy.cs"), "ProductVersion.TaxonomyVersion");
  addMissingExpectation(errors, "ComponentCatalogWinUI/Services/CatalogStoragePaths.cs", readTarget("ComponentCatalogWinUI/Services/CatalogStoragePaths.cs"), "ProductVersion.AndroidVersionCode");
  addMissingExpectation(errors, "ComponentCatalogWinUI/Services/CatalogStoragePaths.cs", readTarget("ComponentCatalogWinUI/Services/CatalogStoragePaths.cs"), "ProductVersion.ProductVersionName");
  addMissingExpectation(errors, "Android/android/app/build.gradle", readTarget("Android/android/app/build.gradle"), "new JsonSlurper().parse(file('../../../version.json'))");
  addMissingExpectation(errors, "Android/android/app/build.gradle", readTarget("Android/android/app/build.gradle"), "versionCode productVersion.android.code");
  addMissingExpectation(errors, "Android/android/app/build.gradle", readTarget("Android/android/app/build.gradle"), "versionName productVersion.product.version");
  try {
    const packageMetadata = JSON.parse(readTarget("Android/package.json"));
    if (packageMetadata.version !== `${normalized.product.version}.0`) {
      errors.push("Android/package.json version does not match version.json");
    }
  } catch {
    errors.push("Android/package.json must contain valid JSON");
  }
  addMissingExpectation(errors, "Android/src/app-update.ts", readTarget("Android/src/app-update.ts"), 'import { ANDROID_VERSION_CODE, PRODUCT_VERSION } from "./version.generated";');
  addMissingExpectation(errors, "Android/src/snapshot-store.ts", readTarget("Android/src/snapshot-store.ts"), 'import { TAXONOMY_VERSION } from "./version.generated";');
  addMissingExpectation(errors, "shared/catalog.ts", readTarget("shared/catalog.ts"), 'import { TAXONOMY_VERSION } from "./version.generated";');
  addMissingExpectation(errors, "Android/src/components/AboutView.tsx", readTarget("Android/src/components/AboutView.tsx"), "CURRENT_APP_VERSION_NAME");
  addMissingExpectation(errors, "ComponentCatalogWinUI/Pages/AboutPage.xaml.cs", readTarget("ComponentCatalogWinUI/Pages/AboutPage.xaml.cs"), "Assembly.GetExecutingAssembly().GetName().Version");

  try {
    const manifest = JSON.parse(readTarget("发布包/Android/app-update.json"));
    if (manifest.versionCode !== normalized.android.code) {
      errors.push("发布包/Android/app-update.json versionCode does not match version.json");
    }
    if (manifest.versionName !== normalized.product.version) {
      errors.push("发布包/Android/app-update.json versionName does not match version.json");
    }
  } catch {
    errors.push("发布包/Android/app-update.json must contain valid JSON");
  }

  return errors;
}

export async function writeGeneratedVersionFiles(repositoryRoot, version) {
  const generatedFiles = expectedGeneratedFiles(version);
  await Promise.all(
    Object.entries(generatedFiles).map(async ([relativePath, content]) =>
      writeFile(join(repositoryRoot, relativePath), content, "utf8"),
    ),
  );
}

export async function synchronizeHostedManifest(repositoryRoot, version) {
  const manifestPath = join(repositoryRoot, "发布包/Android/app-update.json");
  const manifest = JSON.parse(await readFile(manifestPath, "utf8"));
  await writeFile(
    manifestPath,
    `${JSON.stringify({ ...manifest, versionCode: version.android.code, versionName: version.product.version }, null, 2)}\n`,
    "utf8",
  );
}

export async function synchronizeAndroidPackageMetadata(repositoryRoot, version) {
  const packagePath = join(repositoryRoot, "Android/package.json");
  const packageMetadata = JSON.parse(await readFile(packagePath, "utf8"));
  await writeFile(
    packagePath,
    `${JSON.stringify({ ...packageMetadata, version: `${version.product.version}.0` }, null, 2)}\n`,
    "utf8",
  );
}

export async function validateRepositoryVersioning(repositoryRoot) {
  const version = await readVersionFile(join(repositoryRoot, "version.json"));
  const entries = await Promise.all(
    requiredFilePaths.map(async (relativePath) => [relativePath, await readFile(join(repositoryRoot, relativePath), "utf8")]),
  );

  return validateVersionTargets(version, Object.fromEntries(entries));
}

async function main() {
  const mode = process.argv[2] ?? "--check";
  if (mode !== "--check" && mode !== "--write") {
    throw new Error("Usage: node scripts/version.mjs [--check|--write]");
  }

  const repositoryRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
  const version = await readVersionFile(join(repositoryRoot, "version.json"));
  if (mode === "--write") {
    await writeGeneratedVersionFiles(repositoryRoot, version);
    await synchronizeAndroidPackageMetadata(repositoryRoot, version);
    await synchronizeHostedManifest(repositoryRoot, version);
  }

  const errors = await validateRepositoryVersioning(repositoryRoot);
  if (errors.length > 0) {
    throw new Error(`Version metadata drift:\n${errors.map((error) => `- ${error}`).join("\n")}`);
  }

  console.log(`Version metadata is synchronized: product ${version.product.version}, Android code ${version.android.code}, taxonomy ${version.taxonomy.version}.`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  main().catch((error) => {
    console.error(error.message);
    process.exitCode = 1;
  });
}
